"""班车业务函数包 —— 调度器的 **in-process 执行体**（2026-11-16，bus_inprocess_pure_code）。

背景：班车原来是「`/bin/sh` 壳脚本起子进程」（Hermes cron 时代的补丁 —— 当时
解释器环境不可控）。现在调度器住在 console 进程内，这个理由已消失 ⇒ 班车改成
**函数注册**（Quartz 的 JobType 式）：``BUS_JOBS`` 里写的是 ``"模块:可调用"``，
调度器 import 之后**同进程**调用。

四条班车各一个模块：

====================== ========================== ==========================
模块                   干什么                     入口
====================== ========================== ==========================
``distill``            记忆提炼（会话 → LLM → 库） ``run()``
``maintenance``        合并 · 遗忘（维护）        ``run()``
``synonyms``           同义词总线 + jieba 词典    ``run()``
``tiering``            记忆分级（提名 / 升降）    ``run()``
====================== ========================== ==========================

四条纪律（**本包的硬规矩**）：

1. **班车唯一入口是 ``run()``**：契约 ``run() -> (ok, 人读摘要)``。
   ``ok`` 是布尔（这一轮成没成），第二个返回值是**给人看的一句话**
   （落 ``ks_bus_state.detail``），不是 JSON dump。
2. **模块级零副作用**：import 本包下任何模块都**不许**连库 / 发网络请求 /
   起子进程 —— import 只定义函数。**所有动作都发生在 ``run()`` 里面**
   （调度器 import 完才调用它）。
3. **异常照抛**：``run()`` 里真出错就抛（由调度层捕获并落 ``ok=False``），
   不许把失败伪装成 ``(True, ...)` —— 假绿比假红危险得多。
4. **依赖走 keepsake 既有 core**：存储走 ``core.factory.storage_from_config``，
   LLM 走 ``core.llm_http`` / ``core.ops.consolidator``；**不自己搓一套**。

本包**不 import 任何子模块**（懒加载）：import 侧要保持零副作用到极致。
"""

